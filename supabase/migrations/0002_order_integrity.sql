BEGIN;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public'
    AND tablename IN ('orders','drivers','profiles','order_status_history')
    AND policyname NOT IN ('profiles_select_own','profiles_admin_all','orders_admin_all','orders_driver_select_own','orders_driver_update_own','drivers_admin_all','drivers_self_select','drivers_self_update','history_admin_all','history_admin_select','history_driver_select_own','history_driver_insert_own')) THEN
    RAISE EXCEPTION 'Unreviewed legacy policies found. Review check_existing_policies.sql before migrating.';
  END IF;
END;
$$;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS request_key uuid;
ALTER TABLE public.orders ADD COLUMN IF NOT EXISTS request_hash text;
CREATE UNIQUE INDEX IF NOT EXISTS orders_request_key_unique ON public.orders(request_key) WHERE request_key IS NOT NULL;
CREATE OR REPLACE FUNCTION public.prepare_order() RETURNS trigger LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  NEW.order_number := 'NQ-' || NEW.id::text;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS orders_prepare ON public.orders;
CREATE TRIGGER orders_prepare BEFORE INSERT ON public.orders FOR EACH ROW EXECUTE FUNCTION public.prepare_order();
CREATE OR REPLACE FUNCTION public.record_order_status() RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  IF TG_OP = 'INSERT' OR NEW.status IS DISTINCT FROM OLD.status THEN
    INSERT INTO public.order_status_history(order_id,status,changed_by)
    VALUES (NEW.id, NEW.status, coalesce(auth.uid()::text, 'server'));
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS orders_record_status ON public.orders;
CREATE TRIGGER orders_record_status AFTER INSERT OR UPDATE ON public.orders FOR EACH ROW EXECUTE FUNCTION public.record_order_status();
DROP POLICY IF EXISTS history_driver_insert_own ON public.order_status_history;
-- History is generated by the database, never by a browser-supplied actor.
DROP POLICY IF EXISTS history_admin_all ON public.order_status_history;
DROP POLICY IF EXISTS history_admin_select ON public.order_status_history;
CREATE POLICY history_admin_select ON public.order_status_history FOR SELECT USING (public.is_admin());
CREATE OR REPLACE FUNCTION public.consume_request_limit(bucket_key text, max_hits integer, window_seconds integer)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE current_hits integer;
BEGIN
  INSERT INTO public.request_limits(bucket, hits, expires_at)
  VALUES (bucket_key, 1, now() + make_interval(secs => window_seconds))
  ON CONFLICT (bucket) DO UPDATE SET
    hits = CASE WHEN request_limits.expires_at <= now() THEN 1 ELSE request_limits.hits + 1 END,
    expires_at = CASE WHEN request_limits.expires_at <= now() THEN now() + make_interval(secs => window_seconds) ELSE request_limits.expires_at END
  RETURNING hits INTO current_hits;
  DELETE FROM public.request_limits WHERE expires_at < now() - interval '1 day';
  RETURN current_hits > max_hits;
END;
$$;
CREATE TABLE IF NOT EXISTS public.request_limits(bucket text PRIMARY KEY, hits integer NOT NULL, expires_at timestamptz NOT NULL);
ALTER TABLE public.request_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.request_limits FROM anon, authenticated;
REVOKE ALL ON FUNCTION public.consume_request_limit(text,integer,integer) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.consume_request_limit(text,integer,integer) TO service_role;
COMMIT;
