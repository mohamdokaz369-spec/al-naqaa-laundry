-- Fresh installations only: existing tables are left intact.
BEGIN;
CREATE TABLE IF NOT EXISTS public.drivers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL, phone text NOT NULL UNIQUE,
  current_lat double precision, current_lng double precision,
  is_active boolean NOT NULL DEFAULT true,
  last_location_update timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_number text UNIQUE, customer_name text NOT NULL, phone text NOT NULL,
  address text, service_type text NOT NULL, status text NOT NULL DEFAULT 'pending',
  pickup_date date, pickup_time time, expected_delivery_time timestamptz,
  notes text, location_lat double precision, location_lng double precision,
  google_maps_link text, assigned_driver_id bigint REFERENCES public.drivers(id) ON DELETE SET NULL,
  route_order integer, scheduled_at timestamptz, estimated_arrival timestamptz,
  fulfillment_type text DEFAULT 'home_pickup', order_source text DEFAULT 'website', items_count integer,
  created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz
);
CREATE TABLE IF NOT EXISTS public.order_status_history (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id bigint NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  status text NOT NULL, changed_at timestamptz NOT NULL DEFAULT now(), changed_by text NOT NULL, notes text
);
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.drivers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_status_history ENABLE ROW LEVEL SECURITY;
COMMIT;
